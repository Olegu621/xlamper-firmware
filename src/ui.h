#pragma once
// ==================================================================
//  ui.h — анимационный UI-фреймворк v0.12.
//
//  Принципы:
//   * все переходы — рисование в буфер U8g2 + sendBuffer, ~60 fps;
//   * анимации НЕ блокируют ввод: каждый кадр вызывает pollEvent()
//     и отменяются по EV_EXIT (никаких delay в переходах);
//   * easing-функции для плавности.
//
//  Переходы экранов (LaunchStyle):
//   * SLIDE  — старый экран уезжает влево, новый въезжает справа
//   * WIPE  — шторка-заливка слева направо и обратно
//   * ZOOM  — новый экран «проявляется» инверсными полосами
//   * FADE  — мерцающее dissolve (дизеринг 50%)
// ==================================================================
#include <Arduino.h>

enum class LaunchStyle : uint8_t { SLIDE, WIPE, ZOOM, FADE };

// Плавный переход к новому экрану. drawer рисует НОВЫЙ кадр в буфер
// (без display()!). Анимация сама выводит кадры и обрабатывает ввод.
// ctx — произвольный контекст, передаётся в drawer (для лямбд с захватом).
// Возвращает false, если пользователь нажал «выход» в середине.
bool uiTransition(LaunchStyle style, void (*drawer)(void*), void* ctx = nullptr);

// Уведомление-плашка (toast): строка + автозакрытие мс. Не блокирует.
void uiToast(const char* line1, const char* line2, uint16_t ms);

// Тикающий спиннер ожидания (ожидание сети и т.п.). Возвращает false при EV_EXIT.
bool uiSpinner(const char* title, bool (*work)());   // work() -> true = готово

// Прогресс-бар 0..100 в области (x,y,w,h), рисует поверх буфера.
void uiProgress(int x, int y, int w, int h, int pct);
